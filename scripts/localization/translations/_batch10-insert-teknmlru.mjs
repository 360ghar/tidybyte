const english = source.strings;

mkdirSync(SITE_OUT, { recursive: true });

for (const lang of LANGS) {
  const values = SITE[lang];
  if (values.length !== english.length) {
    throw new Error(`${lang}: ${values.length} values for ${english.length} English strings`);
  }
  const map = {};
  english.forEach((key, index) => {
    const value = values[index];
    if (typeof value !== "string" || value.trim() === "") {
      throw new Error(`${lang}: empty value for index ${index} (${key})`);
    }
    if (value !== key && map[key] !== undefined) {
      throw new Error(`${lang}: duplicate key at index ${index}: ${key}`);
    }
    map[key] = value;
  });
  writeFileSync(join(SITE_OUT, `${lang}.json`), `${JSON.stringify(map, null, 2)}\n`);
  console.log(`site-translations/${lang}.json: ${Object.keys(map).length} keys`);
}

