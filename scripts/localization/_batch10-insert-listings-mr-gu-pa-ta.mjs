const raw = JSON.parse(readFileSync(PATH, 'utf8'));
const limits = raw._limits;
const english = raw.en;

let failures = 0;
const check = (lang, field, value) => {
  if (typeof value !== 'string' || value.trim() === '') {
    console.error(`FAIL: ${lang}.${field} is empty`);
    failures += 1;
    return;
  }
  if (value.length > limits[field]) {
    console.error(
      `FAIL: ${lang}.${field} is ${value.length} chars, over the ${limits[field]} limit`,
    );
    failures += 1;
  }
};

for (const [lang, entry] of Object.entries(LANG)) {
  if (!(lang in raw)) {
    console.error(`FAIL: listings.json has no ${lang} entry to fill in`);
    failures += 1;
    continue;
  }
  // name stays TidyByte in every storefront.
  raw[lang] = {
    name: english.name,
    subtitle: entry.subtitle,
    promotionalText: entry.promotionalText,
    description: entry.description,
    keywords: entry.keywords,
    whatsNew: entry.whatsNew,
  };
  for (const [field, value] of Object.entries(raw[lang])) check(lang, field, value);

  // Apple indexes name + subtitle + keywords together, so a term already in the
  // subtitle earns nothing. Only single-word terms are comparable.
  const subtitleWords = new Set(
    entry.subtitle
      .toLowerCase()
      .split(/[^\p{L}\p{N}]+/u)
      .filter((w) => w.length > 2),
  );
  for (const term of entry.keywords.split(',')) {
    const t = term.trim().toLowerCase();
    if (!t.includes(' ') && subtitleWords.has(t)) {
      console.error(`FAIL: ${lang}.keywords repeats the subtitle word ${JSON.stringify(term)}`);
      failures += 1;
    }
  }
  if (/,\s/.test(entry.keywords)) {
    console.error(`FAIL: ${lang}.keywords has a space after a comma`);
    failures += 1;
  }
  console.log(
    `  ${lang}  subtitle ${entry.subtitle.length}/30  promotion ${entry.promotionalText.length}/170  description ${entry.description.length}/4000  keywords ${entry.keywords.length}/100  whatsNew ${entry.whatsNew.length}/4000`,
  );
}

if (failures > 0) {
  console.error(`\n${failures} problem(s); listings.json not written.`);
  process.exit(1);
}

writeFileSync(PATH, `${JSON.stringify(raw, null, 2)}\n`);
console.log(`\nwritten ${PATH}`);
